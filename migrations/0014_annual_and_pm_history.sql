-- Keep annual/inspection reminders independent from the PM/service cycle.
CREATE TABLE IF NOT EXISTS equipment_annual_settings (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  equipment_id INTEGER NOT NULL UNIQUE,
  interval_days INTEGER NOT NULL DEFAULT 365 CHECK (interval_days > 0),
  active INTEGER NOT NULL DEFAULT 1,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (equipment_id) REFERENCES equipment(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_equipment_annual_active
ON equipment_annual_settings(active);

-- Preserve annual reminders that were configured by the first PM scheduler.
INSERT OR IGNORE INTO equipment_annual_settings (equipment_id, interval_days, active, updated_at)
SELECT equipment_id, 365, 1, CURRENT_TIMESTAMP
FROM equipment_pm_settings
WHERE annual_required = 1;

-- The legacy flag remains for compatibility, but annual scheduling is now controlled separately.
UPDATE equipment_pm_settings
SET annual_required = 0, updated_at = CURRENT_TIMESTAMP
WHERE annual_required <> 0;

