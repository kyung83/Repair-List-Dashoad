        AND a.matched_equipment_id = pm_status.equipment_id
      LIMIT 1
    ), pm_status.last_mileage),
    service_date = (
      SELECT a.service_date
      FROM pm_history_import_audit a
      WHERE a.import_batch = 'pm-sheet-2026-08-07'
        AND a.matched_equipment_id = pm_status.equipment_id
      LIMIT 1
    ),
    status = CASE WHEN COALESCE(trim(status), '') = '' THEN 'History imported' ELSE status END,
    updated_at = CURRENT_TIMESTAMP
WHERE EXISTS (
  SELECT 1
  FROM pm_history_import_audit a
  WHERE a.import_batch = 'pm-sheet-2026-08-07'
    AND a.matched_equipment_id = pm_status.equipment_id
    AND (
      pm_status.service_date IS NULL
      OR a.service_date > pm_status.service_date
      OR (a.service_date = pm_status.service_date AND pm_status.last_mileage IS NULL AND a.last_mileage IS NOT NULL)
    )
);

-- Mirror the best known PM service date onto equipment, without changing current Geotab mileage.
UPDATE equipment
SET service_date = (
      SELECT ps.service_date FROM pm_status ps WHERE ps.equipment_id = equipment.id
    ),
    updated_at = CURRENT_TIMESTAMP
WHERE id IN (
  SELECT matched_equipment_id
  FROM pm_history_import_audit
  WHERE import_batch = 'pm-sheet-2026-08-07'
    AND matched_equipment_id IS NOT NULL
)
AND EXISTS (
  SELECT 1
  FROM pm_status ps
  WHERE ps.equipment_id = equipment.id
    AND ps.service_date IS NOT NULL
    AND (equipment.service_date IS NULL OR ps.service_date > equipment.service_date)
);
