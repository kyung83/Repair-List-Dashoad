CREATE TABLE _truck_pm_resolution_20261111 AS
WITH units AS (
  SELECT DISTINCT source_unit
  FROM _truck_pm_stage_20261111
  WHERE event_date IS NOT NULL
),
candidates AS (
  SELECT u.source_unit,e.id AS equipment_id,
         CASE
           WHEN upper(trim(e.unit))=upper(trim(u.source_unit)) THEN 1
           WHEN substr(trim(u.source_unit),1,1) BETWEEN '0' AND '9'
             AND instr(u.source_unit,'(')>0
             AND trim(CASE WHEN instr(e.unit,'(')>0
                           THEN substr(e.unit,1,instr(e.unit,'(')-1)
                           ELSE e.unit END)
                 =trim(substr(u.source_unit,1,instr(u.source_unit,'(')-1))
             THEN 2
           ELSE 99
         END AS score
  FROM units u
  JOIN equipment e
    ON e.active=1
   AND e.archived_at IS NULL
   AND lower(COALESCE(e.equipment_type,'truck'))<>'trailer'
   AND e.geotab_trailer_id IS NULL
  WHERE upper(trim(e.unit))=upper(trim(u.source_unit))
     OR (
       substr(trim(u.source_unit),1,1) BETWEEN '0' AND '9'
       AND instr(u.source_unit,'(')>0
       AND trim(CASE WHEN instr(e.unit,'(')>0
                     THEN substr(e.unit,1,instr(e.unit,'(')-1)
                     ELSE e.unit END)
           =trim(substr(u.source_unit,1,instr(u.source_unit,'(')-1))
     )
),
best AS (
  SELECT source_unit,MIN(score) AS best_score
  FROM candidates
  GROUP BY source_unit
),
grouped AS (
  SELECT u.source_unit,
         COUNT(c.equipment_id) AS candidate_count,
         CASE WHEN COUNT(c.equipment_id)=1 THEN MAX(c.equipment_id) END AS equipment_id
  FROM units u
  LEFT JOIN best b ON b.source_unit=u.source_unit
  LEFT JOIN candidates c ON c.source_unit=u.source_unit AND c.score=b.best_score
  GROUP BY u.source_unit
)
SELECT * FROM grouped;

