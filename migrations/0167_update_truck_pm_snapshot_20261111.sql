-- Recompute the current PM baseline only for units represented by this snapshot.
-- The newest PM from ALL history wins, so a newer app-entered PM can never be rolled backward.
-- If a custom profile does not contain the latest historical PM type, preserve the configured next type.
WITH ranked AS (
  SELECT me.equipment_id,me.pm_type,me.event_date,me.mileage,
         ROW_NUMBER() OVER (
           PARTITION BY me.equipment_id
           ORDER BY me.event_date DESC,me.id DESC
         ) AS rn
  FROM maintenance_events me
  WHERE me.event_type='pm'
    AND me.equipment_id IN (
      SELECT equipment_id
      FROM _truck_pm_resolution_20261111
      WHERE equipment_id IS NOT NULL
    )
    AND me.event_date<=date('now')
),
latest AS (
  SELECT equipment_id,pm_type,event_date,mileage
  FROM ranked
  WHERE rn=1
),
resolved AS (
  SELECT l.equipment_id,l.event_date,l.mileage,
         CASE
           WHEN p.sequence_json IS NULL
             OR json_valid(p.sequence_json)=0
             OR json_array_length(p.sequence_json)=0
           THEN CASE l.pm_type
             WHEN '40' THEN '20A'
             WHEN '20A' THEN '20B'
             WHEN '20B' THEN '40'
             ELSE COALESCE(ps.pm_type,l.pm_type)
           END
           WHEN NOT EXISTS (
             SELECT 1 FROM json_each(p.sequence_json) j
             WHERE CAST(j.value AS TEXT)=l.pm_type
           )
           THEN COALESCE(NULLIF(ps.pm_type,''),CAST(json_extract(p.sequence_json,'$[0]') AS TEXT))
           ELSE CAST(json_extract(
             p.sequence_json,
             '$[' || (
               (
                 (SELECT CAST(j.key AS INTEGER)
                  FROM json_each(p.sequence_json) j
                  WHERE CAST(j.value AS TEXT)=l.pm_type
                  LIMIT 1) + 1
               ) % json_array_length(p.sequence_json)
             ) || ']'
           ) AS TEXT)
         END AS next_pm_type
  FROM latest l
  LEFT JOIN equipment_pm_settings s ON s.equipment_id=l.equipment_id
  LEFT JOIN pm_profiles p ON p.id=s.profile_id
  LEFT JOIN pm_status ps ON ps.equipment_id=l.equipment_id
)
INSERT INTO pm_status
  (equipment_id,pm_type,status,last_mileage,service_date,updated_at)
SELECT equipment_id,next_pm_type,'Current',mileage,event_date,CURRENT_TIMESTAMP
FROM resolved
WHERE 1=1
ON CONFLICT(equipment_id) DO UPDATE SET
  pm_type=excluded.pm_type,
  status='Current',
  last_mileage=COALESCE(excluded.last_mileage,pm_status.last_mileage),
  service_date=excluded.service_date,
  updated_at=CURRENT_TIMESTAMP;

WITH ranked AS (
  SELECT me.equipment_id,me.event_date,
         ROW_NUMBER() OVER (
           PARTITION BY me.equipment_id
           ORDER BY me.event_date DESC,me.id DESC
         ) AS rn
  FROM maintenance_events me
  WHERE me.event_type='pm'
    AND me.equipment_id IN (
      SELECT equipment_id
      FROM _truck_pm_resolution_20261111
      WHERE equipment_id IS NOT NULL
    )
    AND me.event_date<=date('now')
)
UPDATE equipment
SET service_date=(
      SELECT event_date
      FROM ranked
      WHERE ranked.equipment_id=equipment.id AND rn=1
    ),
    updated_at=CURRENT_TIMESTAMP
WHERE id IN (
  SELECT equipment_id FROM ranked WHERE rn=1
);

